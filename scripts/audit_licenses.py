#!/usr/bin/env python3
"""Audit cached Cargo dependency licenses for the supported Linux target.

This checks dependency manifests and preserves their notices. It cannot establish
whether the application's own source was independently authored.
"""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parent.parent
TARGET = 'x86_64-unknown-linux-gnu'
NOTICES = ROOT / 'THIRD_PARTY_NOTICES.md'
# Each expression offers MIT at the crate level; file-level exceptions follow.
# Deliberately do not accept a license merely because it contains the word MIT.
MIT_CHOICES = {
    'MIT',
    'MIT OR Apache-2.0',
    'Unlicense OR MIT',
    'Apache-2.0/MIT',  # Legacy Cargo spelling used by signal-hook 0.3.18.
    'Apache-2.0 WITH LLVM-exception OR Apache-2.0 OR MIT',
}
# File-level terms are not necessarily described by a crate's manifest.
# Pin these reviewed exceptions so a dependency update requires another review.
# The rustix entry preserves only the licensing header, hashing the full file.
EXTRA_NOTICES = {
    'regex-syntax': ('0.8.11', [('src/unicode_tables/LICENSE-UNICODE', None)]),
    'rustix': ('0.38.44', [('src/backend/linux_raw/vdso.rs', 7)]),
}


def collect():
    proc = subprocess.run(
        ['cargo', 'metadata', '--offline', '--locked', '--format-version', '1',
         '--filter-platform', TARGET],
        cwd=ROOT, check=True, capture_output=True, text=True,
    )
    metadata = json.loads(proc.stdout)
    root_id = metadata['resolve']['root']
    reachable = set()
    nodes = {node['id']: node for node in metadata['resolve']['nodes']}
    pending = [root_id]
    while pending:
        pkg_id = pending.pop()
        if pkg_id in reachable:
            continue
        reachable.add(pkg_id)
        pending.extend(nodes[pkg_id]['dependencies'])

    entries = []
    for pkg in sorted(metadata['packages'], key=lambda p: (p['name'], p['version'])):
        if pkg['id'] == root_id or pkg['id'] not in reachable:
            continue
        expression = pkg.get('license')
        if expression not in MIT_CHOICES:
            raise ValueError(f"Review required: {pkg['name']} {pkg['version']}: {expression!r}")
        directory = Path(pkg['manifest_path']).parent
        primary = directory / 'LICENSE-MIT'
        if not primary.is_file():
            primary = directory / 'LICENSE'
        if not primary.is_file():
            raise ValueError(f"No MIT license text: {pkg['name']} {pkg['version']}")
        text = primary.read_text(encoding='utf-8')
        if 'Permission is hereby granted' not in text:
            raise ValueError(f"Unrecognized MIT notice: {primary}")
        files = [(primary.name, text, hashlib.sha256(primary.read_bytes()).hexdigest())]
        for name in ['COPYRIGHT', 'COPYING', 'NOTICE']:
            path = directory / name
            if path.is_file():
                files.append((name, path.read_text(encoding='utf-8'), hashlib.sha256(path.read_bytes()).hexdigest()))
        exceptions = EXTRA_NOTICES.get(pkg['name'])
        reviewed_paths = set()
        if exceptions:
            version, notices = exceptions
            if pkg['version'] != version:
                raise ValueError(f"Review file-level terms: {pkg['name']} {pkg['version']}")
            for relative, header_lines in notices:
                path = directory / relative
                text = path.read_text(encoding='utf-8')
                label = relative
                if header_lines is not None:
                    text = '\n'.join(text.splitlines()[:header_lines]) + '\n'
                    label += ' (license header only)'
                files.append((label, text, hashlib.sha256(path.read_bytes()).hexdigest()))
                reviewed_paths.add(relative)
        # Do not silently drop an additional license placed below the crate root.
        for path in sorted(directory.rglob('*')):
            if (path.is_file() and path.parent != directory
                    and path.name.startswith(('LICENSE', 'COPYRIGHT', 'COPYING', 'NOTICE'))
                    and path.relative_to(directory).as_posix() not in reviewed_paths):
                raise ValueError(f"Review additional notice: {pkg['name']}: {path.relative_to(directory)}")
        entries.append((pkg['name'], pkg['version'], expression, files))
    return entries


def render(entries):
    out = [
        '# Third-party notices\n',
        'Generated by `python3 scripts/audit_licenses.py --write`.\n',
        f'Scope: Cargo dependencies resolved for `{TARGET}` from `Cargo.lock`. '
        'MIT is selected for crate-level alternative licenses; additional file-level terms remain applicable. '
        'These upstream notices do not establish the provenance of Runo source code.\n',
        'File-level notices include the Unicode license for `regex-syntax` data tables '
        'and the CC0-1.0 licensing header for the `rustix` vDSO parser.\n',
        'System libraries, Rust toolchain/runtime components, external commands, '
        'and user-installed `.nanorc` files are outside this Cargo inventory.\n',
    ]
    for name, version, expression, files in entries:
        out.append(f'## {name} {version}\n')
        out.append(f'Declared: `{expression}`. Selected: `MIT`.\n')
        for filename, text, digest in files:
            out.append(f'### {filename}\n')
            out.append(f'SHA-256 of upstream file: `{digest}`\n')
            out.append('```text\n' + text.rstrip() + '\n```\n')
    return '\n'.join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true', help='Refresh checked-in dependency notices')
    args = parser.parse_args()
    try:
        entries = collect()
        expected = render(entries)
        if args.write:
            NOTICES.write_text(expected, encoding='utf-8')
        elif not NOTICES.is_file() or NOTICES.read_text(encoding='utf-8') != expected:
            raise ValueError('THIRD_PARTY_NOTICES.md is missing or stale; review changes before using --write')
    except (OSError, ValueError, subprocess.CalledProcessError) as exc:
        print(f'Dependency license audit failed: {exc}', file=sys.stderr)
        if isinstance(exc, subprocess.CalledProcessError) and exc.stderr:
            print(exc.stderr, file=sys.stderr)
        return 1
    print(f'PASS: {len(entries)} crate-level licenses offer MIT for {TARGET}; upstream notices preserved.')
    print('File-level Unicode and CC0 notices are also preserved.')
    print('Application source provenance is outside this check; see LICENSE-AUDIT.md.')
    return 0


if __name__ == '__main__':
    sys.exit(main())
